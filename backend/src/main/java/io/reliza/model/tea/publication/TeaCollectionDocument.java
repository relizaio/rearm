package io.reliza.model.tea.publication;

import java.io.Serializable;
import java.util.List;
import java.util.UUID;

import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonPropertyOrder;

import io.reliza.model.tea.TeaCollectionBelongsToType;

/**
 * The TEA 1.0.0 {@code collection} object exactly as a published collection version serves it
 * (task TEA-5). Built from these records rather than the generated {@code model/tea} classes,
 * which are the 0.4.0 shape and are regenerated by part 5: a frozen document must be 1.0.0-exact
 * now and must not change when those classes do. Serialized once with {@code Utils.OM} and
 * stored; the field order is fixed here.
 */
@JsonInclude(JsonInclude.Include.NON_NULL)
@JsonPropertyOrder({ "uuid", "version", "createdDate", "belongsTo", "updateReason", "artifacts" })
public record TeaCollectionDocument(UUID uuid, int version, String createdDate, TeaCollectionBelongsToType belongsTo,
		TeaUpdateReasonDocument updateReason, List<TeaArtifactDocument> artifacts) implements Serializable {
}
