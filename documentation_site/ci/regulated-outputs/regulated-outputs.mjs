// Declared identifiers of the record that name a pin of rebom, the service that merges release SBOMs and runs
// the checking engine: computed here from rebom-backend at the same commit as the record (rebomPins), and
// compared by `pins`, `section` and `release`, which read git. The documentation image has no rebom-backend:
// `pages` only holds that each is declared, and in no other list.
export const PINS = ['rebom-engine', 'rebom-engine-image', 'rebom-tools']
export const DOCKERFILE = 'rebom-backend/Dockerfile'
const TOOLS_FILE = /^rebom-backend\/tools\.([a-z0-9_]+)\.sha256$/
// Under a release pin the engine is the release's zip, whose sums rebom-tools holds; no image of this file builds it.
export const RELEASE_ZIP = 'release-zip'

const TITLE = /^# Regulated output changes \(ReARM Pro\), record at RO-([1-9][0-9]*)$/
const KEY_ROW = /^\| `([a-z0-9-]+)` \| ([A-Za-z0-9._:-]{1,80}|\(not held\)) \| .* \| (computed|raised|declared): [^|]+ \|$/
const ENTRY = /^### RO-([1-9][0-9]*): (.+)$/
const ACTION = /^- What to do: (.+)$/

export function sha256(bytes) {
    return createHash('sha256').update(bytes).digest('hex')
}

// The record as the generator writes it; anything else throws, because the copy is held to the
// generated bytes and a file this cannot read is not that copy.
export function parseRecord(text) {
    if (typeof text !== 'string' || text.includes('\r') || !text.endsWith('\n')) {
        throw new Error('the change record is not the generated file: it has a carriage return or no line feed at its end')
    }
    const lines = text.split('\n')
    const title = TITLE.exec(lines[0])
    if (!title) throw new Error('the change record does not start with its title line')
    const last = Number(title[1])
    const keysAt = lines.indexOf('## Identifiers')
    const changesAt = lines.indexOf('## Changes')
    if (keysAt < 0 || changesAt < keysAt || lines.lastIndexOf('## Identifiers') !== keysAt
        || lines.lastIndexOf('## Changes') !== changesAt) {
        throw new Error('the change record does not have its two sections once each, in order')
    }
    const keys = new Map()
    const held = new Map()
    for (const line of lines.slice(keysAt + 1, changesAt)) {
        if (!line.startsWith('| `')) continue
        const row = KEY_ROW.exec(line)
        if (!row) throw new Error('the change record has an identifier row this check cannot read: ' + line)
        if (keys.has(row[1])) throw new Error('the change record lists ' + row[1] + ' twice')
        keys.set(row[1], row[2])
        held.set(row[1], row[3])
    }
    const entries = []
    for (let i = changesAt + 1; i < lines.length; i++) {
        const head = ENTRY.exec(lines[i])
        if (!head) {
            if (lines[i].startsWith('#')) throw new Error('the change record has a heading that is no entry: ' + lines[i])
            if (entries.length > 0) entries[entries.length - 1].lines.push(lines[i])
            continue
        }
        entries.push({ number: Number(head[1]), title: head[2], lines: [lines[i]] })
    }
    entries.forEach((e, i) => {
        if (e.number !== i + 1) throw new Error('entry ' + (i + 1) + ' of the change record is numbered RO-' + e.number)
        const actions = e.lines.map(l => ACTION.exec(l)).filter(m => m)
        if (actions.length !== 1) throw new Error('RO-' + e.number + ' does not say what to do exactly once')
        e.action = actions[0][1]
        e.block = e.lines.join('\n')
        delete e.lines
    })
    if (entries.length !== last) {
        throw new Error('the change record says it stands at RO-' + last + ' and holds ' + entries.length + ' entries')
    }
    return { last, keys, held, entries }
}

// The line of a release that adds no entry. It says what the record can say: that no entry was added.
// A change that moved no identifier and that nobody recorded is not in the record, and the line says so.
export const NO_ENTRY = last => 'ReARM Pro: no new entry in the change record in this release; it stands at RO-' + last + ' (' + URL
    + '). This does not say that no output changed: the page lists what the record does not hold.'

// The section the release notes of a release must hold: the entries its record adds to the record
// of the release before it (null: no record before). Throws when an entry a release carried is
// gone or changed. It cannot know why (an entry taken out or edited after its release, or a commit on an
// older line that never had the entry or numbered one of its own), so the two sentences name both.
const GONE = ' was in the release before and is not in this record: it was taken out after that release, or this commit is on an older line than that release. A release carries every entry of the release before it, unchanged'
const CHANGED = ' is not the entry the release before carried under that number: it was edited after that release, or this commit is on an older line that numbered an entry of its own. A release carries every entry of the release before it, unchanged'
export function expectedSection(before, now) {
    const carried = before ? before.entries : []
    for (const old of carried) {
        const same = now.entries[old.number - 1]
        if (!same) throw new Error('RO-' + old.number + GONE)
        if (same.block !== old.block) throw new Error('RO-' + old.number + CHANGED)
    }
    const added = now.entries.slice(carried.length)
    if (added.length === 0) {
        return [HEADING, '', NO_ENTRY(now.last)].join('\n')
    }
    const first = added[0].number
    const range = added.length === 1 ? 'entry RO-' + first : 'entries RO-' + first + ' to RO-' + now.last
    return [HEADING, '', 'ReARM Pro, change record ' + range + ' (' + URL + '):', '',
        ...added.map(e => '- RO-' + e.number + ': ' + e.title + '. What to do: ' + e.action)].join('\n')
}

// Which lines of a body a reader of the rendered page does not see as text: lines inside a fenced
// code block, and lines any part of which is inside an HTML comment.
export function hiddenLines(lines) {
    const hidden = lines.map(() => false)
    let fence = null
    let inComment = false
    lines.forEach((line, i) => {
        if (fence) {
            hidden[i] = true
            const close = /^ {0,3}(`{3,}|~{3,})\s*$/.exec(line)
            if (close && close[1][0] === fence[0] && close[1].length >= fence.length) fence = null
            return
        }
        let rest = line
        if (inComment) {
            hidden[i] = true
            const end = rest.indexOf('-->')
            if (end < 0) return
            inComment = false
            rest = rest.slice(end + 3)
        } else {
            // a line that opens a fence is a fence whatever follows the marks on it
            const open = /^ {0,3}(`{3,}|~{3,})/.exec(line)
            if (open) {
                fence = open[1]
                hidden[i] = true
                return
            }
        }
        for (;;) {
            const start = rest.indexOf('<!--')
            if (start < 0) break
            hidden[i] = true
            const end = rest.indexOf('-->', start + 4)
            if (end < 0) { inComment = true; break }
            rest = rest.slice(end + 3)
        }
    })
    return hidden
}

const NEAR_HEADING = /^[\s>]*#{0,6}\s*\**\s*regulated[\s-]+outputs?[\s-]+changes?\s*\**\s*:?\s*#*\s*$/i

// Every way a release body fails to carry the section; empty when it carries it. A line of the notes
// is quoted as a JSON string: the log of a workflow run never gets a raw control character of it.
export function bodyFailures(body, section) {
    if (typeof body !== 'string') return ['the release has no notes']
    const lines = body.replace(/\r\n/g, '\n').split('\n')
    const want = section.split('\n')
    const hidden = hiddenLines(lines)
    const out = []
    const at = []
    lines.forEach((line, i) => {
        if (line === HEADING) at.push(i)
        else if (NEAR_HEADING.test(line)) {
            out.push('line ' + (i + 1) + ' looks like the heading and is not it: write exactly `' + HEADING + '` on a line of its own')
        }
    })
    if (at.length === 0) return [...out, 'the release notes have no line `' + HEADING + '`']
    if (at.length > 1) return [...out, 'the release notes have the line `' + HEADING + '` ' + at.length + ' times']
    const start = at[0]
    for (let k = 0; k < want.length; k++) {
        const found = lines[start + k]
        if (found !== want[k]) {
            out.push('line ' + (start + k + 1) + ' of the release notes is not the line the change record gives: expected `'
                + want[k] + '`, found ' + (found === undefined ? 'the end of the notes' : JSON.stringify(found)))
            break
        }
        if (hidden[start + k]) {
            out.push('line ' + (start + k + 1) + ' of the release notes is inside a code block or a comment: a reader does not see it')
            break
        }
    }
    for (let i = start + want.length; i < lines.length && !/^#{1,6}\s/.test(lines[i]); i++) {
        if (/^\s*[-*+]\s+RO-[0-9]/.test(lines[i])) {
            out.push('line ' + (i + 1) + ' of the release notes names an entry the change record does not add in this release')
        }
    }
    return out
}

// Whether the pages the record names by an identifier are the pages this documentation carries. The sentence
// for a page the record does not name gives both ways the record follows a change: the documentation build
// has no git and cannot know whether a release carries the record yet.
export function pageFailures(record, pages, notCompared = {}, pins = []) {
    const out = []
    for (const [key, kind] of record.held) {
        const compared = Object.hasOwn(pages, key)
        const pinned = pins.includes(key)
        const excused = Object.hasOwn(notCompared, key)
        if (pinned && excused) out.push(key + ' is in PINS and in NOT_COMPARED')
        if (kind === 'declared' && !compared && !pinned && !excused) {
            out.push('the change record declares ' + key + ' and this documentation compares it with nothing: add its page to PAGES, or'
                + ' the identifier to NOT_COMPARED with the reason')
        }
        if (compared && excused) out.push(key + ' is in PAGES and in NOT_COMPARED')
        if (excused && kind !== 'declared') out.push('NOT_COMPARED names ' + key + ', which the change record does not declare')
    }
    for (const key of Object.keys(notCompared)) {
        if (!record.held.has(key)) out.push('NOT_COMPARED names ' + key + ', which the change record does not have')
    }
    for (const key of pins) {
        if (Object.hasOwn(pages, key)) out.push(key + ' is in PINS and in PAGES')
        if (!record.held.has(key)) out.push('PINS names ' + key + ', which the change record does not have')
        else if (record.held.get(key) !== 'declared') out.push('PINS names ' + key + ', which the change record does not declare')
    }
    for (const [key, bytes] of Object.entries(pages)) {
        const named = record.keys.get(key)
        if (named === undefined) out.push('the change record has no identifier ' + key)
        else if (bytes === null) out.push('the change record names ' + key + ' and the documentation has no such page')
        else if (sha256(bytes) !== named) {
            out.push('the change record names ' + key + ' as ' + named + ' and the page in this documentation is ' + sha256(bytes)
                + ': the page changed and the record does not follow it yet, or the copy of the record here is older than the record of ReARM Pro. The record follows a change in ReARM Pro first (before the first ReARM release that carries RO-1, in RO-1, in place; from that release on, in a new entry), then it is copied here')
        }
    }
    return out
}

// The instructions of a Dockerfile, each { keyword, args }: comment lines dropped (also inside an instruction
// continued with a backslash), continued lines joined, the keyword in capitals (Docker reads it in any case).
export function dockerInstructions(text) {
    const out = []
    let current = null
    for (const raw of text.replace(/\r\n/g, '\n').split('\n')) {
        if (/^\s*#/.test(raw) || raw.trim() === '') continue
        const line = raw.replace(/\s+$/, '')
        const continued = line.endsWith('\\')
        const part = continued ? line.slice(0, -1) : line
        current = current === null ? part : current + ' ' + part
        if (!continued) {
            out.push(current.trim())
            current = null
        }
    }
    if (current !== null) out.push(current.trim())
    return out.map(t => {
        const m = /^(\S+)\s*([\s\S]*)$/.exec(t)
        return { keyword: m[1].toUpperCase(), args: m[2] }
    })
}

const words = args => args.split(/\s+/).filter(w => w !== '')
const unquoted = v => (v.length >= 2 && (v[0] === '"' || v[0] === "'") && v[v.length - 1] === v[0]) ? v.slice(1, -1) : v

// The values an ARG instruction gives a name: [] when it does not name it, [undefined] for a name without a value.
function argValues(ins, name) {
    if (ins.keyword !== 'ARG') return []
    return words(ins.args).filter(w => w === name || w.startsWith(name + '=')).map(w => w === name ? undefined : unquoted(w.slice(name.length + 1)))
}

// The pins of rebom in one commit: `dockerfile` the text of rebom-backend/Dockerfile (null: not in the commit),
// `tools` the text of each rebom-backend/tools.<arch>.sha256 by its arch. Returns { values, failures }: a pin
// this cannot find or read is a failure, never a value left out, so a file moved or a line renamed is refused.
export function rebomPins(dockerfile, tools) {
    const values = {}
    const failures = []
    if (dockerfile === null) {
        return { values, failures: [DOCKERFILE + ' is not in this commit: the pins of rebom cannot be read. If rebom is built from'
            + ' another file now, this check has to learn it'] }
    }
    const ins = dockerInstructions(dockerfile)
    const commits = []
    const versions = []
    ins.forEach((one, i) => {
        argValues(one, 'REARM_CLI_COMMIT').forEach(value => commits.push({ at: i, value }))
        argValues(one, 'REARM_CLI_VERSION').forEach(value => versions.push({ at: i, value }))
    })
    const arches = Object.keys(tools).sort()
    if (commits.length > 1) {
        failures.push(DOCKERFILE + ' sets REARM_CLI_COMMIT ' + commits.length + ' times: the engine pin is one line')
    } else if (commits.length === 1) {
        // the source pin: the engine is built from this commit, in the stage the ARG belongs to
        const value = commits[0].value
        if (value === undefined || !/^[0-9a-f]{40}$/.test(value)) {
            failures.push(DOCKERFILE + ' sets REARM_CLI_COMMIT to ' + JSON.stringify(value === undefined ? '' : value)
                + ', which is not a commit of 40 lowercase hex digits (the build refuses it too)')
        } else values['rebom-engine'] = value
        const stage = ins.slice(0, commits[0].at).filter(one => one.keyword === 'FROM').pop()
        const digest = stage ? /@sha256:([0-9a-f]{64})(\s|$)/.exec(stage.args) : null
        if (!digest) {
            failures.push('the stage of ' + DOCKERFILE + ' that builds the engine (the one that sets REARM_CLI_COMMIT) does not name its'
                + ' image by a sha256 digest')
        } else values['rebom-engine-image'] = 'sha256:' + digest[1]
    } else if (versions.length === 1 && isProductTag(versions[0].value)) {
        // the release pin: the engine is a release's zip, held by its sums for every arch
        const version = versions[0].value
        values['rebom-engine'] = version
        values['rebom-engine-image'] = RELEASE_ZIP
        for (const arch of arches) {
            const zip = 'rearm-' + version + '-linux-' + arch + '.zip'
            if (!tools[arch].split(/\r?\n/).some(l => l.trim().split(/\s+/).pop().replace(/^\*/, '') === zip)) {
                failures.push('the release pin ' + version + ' of ' + DOCKERFILE + ' has no sum of ' + zip + ' in rebom-backend/tools.'
                    + arch + '.sha256')
            }
        }
    } else {
        failures.push(DOCKERFILE + ' has no engine pin this check knows: neither ARG REARM_CLI_COMMIT with a commit nor one ARG'
            + ' REARM_CLI_VERSION with a release YY.MM.N. If rebom pins its engine another way now, this check has to learn it')
    }
    // the tools: the sums file of the build's arch is copied in and checked with sha256sum -c
    const copy = ins.find(one => one.keyword === 'COPY' && words(one.args).length === 2 && words(one.args)[0] === 'tools.${TARGETARCH}.sha256')
    if (!copy) {
        failures.push(DOCKERFILE + ' does not copy tools.${TARGETARCH}.sha256: the sums of the tools rebom downloads are not where this'
            + ' check reads them. If they moved, this check has to learn it')
    } else {
        const target = words(copy.args)[1]
        const checked = ins.some(one => one.keyword === 'RUN' && words(one.args.replace(/[;&|()]/g, ' ')).some((w, i, all) =>
            w === 'sha256sum' && all[i + 1] === '-c' && all[i + 2] === target))
        if (!checked) failures.push(DOCKERFILE + ' copies tools.${TARGETARCH}.sha256 to ' + target + ' and no RUN checks it with sha256sum -c')
    }
    if (arches.length === 0) failures.push('rebom-backend has no tools.<arch>.sha256 in this commit')
    let canonical = ''
    let readable = true
    for (const arch of arches) {
        const sums = new Map()
        const lines = tools[arch].split(/\r?\n/).filter(l => l.trim() !== '')
        for (const line of lines) {
            const m = /^\s*([0-9a-f]{64})\s+\*?(\S(?:.*\S)?)\s*$/.exec(line)
            if (!m) {
                failures.push('rebom-backend/tools.' + arch + '.sha256 has a line this check cannot read (a sum of 64 lowercase hex digits,'
                    + ' then the file): ' + JSON.stringify(line))
                readable = false
            } else if (sums.has(m[2])) {
                failures.push('rebom-backend/tools.' + arch + '.sha256 names ' + m[2] + ' twice')
                readable = false
            } else sums.set(m[2], m[1])
        }
        if (lines.length === 0) {
            failures.push('rebom-backend/tools.' + arch + '.sha256 holds no sum')
            readable = false
        }
        for (const name of [...sums.keys()].sort()) canonical += arch + ' ' + sums.get(name) + ' ' + name + '\n'
    }
    if (arches.length > 0 && readable) values['rebom-tools'] = sha256(canonical)
    return { values, failures }
}

export const PIN_MOVED = (where, key, now, named) => 'rebom-backend at ' + where + ' gives ' + key + ' ' + now + ' and the change record'
    + ' there says ' + named + ': a pin of rebom moved without its entry, or the copy of the record here is older than the record of'
    + ' ReARM Pro. The record follows the move in ReARM Pro first (before the first ReARM release that carries RO-1, in RO-1, in'
    + ' place; from that release on, in a new entry), then the copy here follows in the same pull request as the move'

// Whether the record names the pins rebom has in the same commit: every identifier of PINS, declared, with the value
// rebomPins computes, compared whole. `where` names the commit or tag for the messages.
export function pinFailures(record, pins, where, keys = PINS) {
    const out = pins.failures.map(f => f + ' (at ' + where + ')')
    for (const key of keys) {
        const named = record.keys.get(key)
        if (named === undefined) {
            out.push('the change record at ' + where + ' has no identifier ' + key + ': it names the pins of rebom from RO-1 on')
            continue
        }
        if (record.held.get(key) !== 'declared') out.push('the change record at ' + where + ' holds ' + key + ' as ' + record.held.get(key)
            + ': a pin of rebom is declared')
        const now = pins.values[key]
        if (now !== undefined && now !== named) out.push(PIN_MOVED(where, key, now, named))
    }
    return out
}

// The pins of rebom at a ref, through git: the Dockerfile and every tools.<arch>.sha256 of rebom-backend.
export function rebomPinsAt(repo, ref) {
    const tools = {}
    for (const path of repo.list(ref, 'rebom-backend')) {
        const m = TOOLS_FILE.exec(path)
        if (m) tools[m[1]] = repo.read(ref, path)
    }
    return rebomPins(repo.read(ref, DOCKERFILE), tools)
}

// A ReARM product release tag: two digits, two digits, a number without a leading zero.
export function isProductTag(tag) {
    return typeof tag === 'string' && /^[0-9]{2}\.[0-9]{2}\.(0|[1-9][0-9]{0,5})$/.test(tag)
}

function parts(tag) {
    return tag.split('.').map(Number)
}

function compareTags(a, b) {
    const x = parts(a)
    const y = parts(b)
    for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i]
    return 0
}

// The product tag right before `tag` among `tags`, by its three numbers; null when there is none.
export function previousTag(tags, tag) {
    const lower = tags.filter(t => isProductTag(t) && compareTags(t, tag) < 0).sort(compareTags)
    return lower.length === 0 ? null : lower[lower.length - 1]
}

export const NOT_THE_FORM = tag => 'the tag ' + JSON.stringify(tag) + ' starts with a digit and is not of the form YY.MM.N of a ReARM'
    + ' release: nothing was checked. If ReARM numbers its releases another way now, this check has to learn it'
export const TAG_NOT_HERE = tag => 'the tag ' + tag + ' is not in this checkout: fetch the tags'
// For the author of the notes, who runs `section` before the release is published: the tag is made at
// publication, so there is nothing to fetch yet.
export const TAG_NOT_MADE = tag => 'the tag ' + tag + ' is not in this checkout. Before the release is published the tag does not exist:'
    + ' run `section ' + tag + ' --at <the commit the release will be made from>`. After it is published: git fetch --tags'

// The check of one release: `repo` reads git (tags(), shallow(), commit(rev) -> 40 hex digits or null,
// read(ref, path) -> text or null). `options.at`: read the record of the release from that commit and
// not from the tag, which need not exist; `options.author`: the caller is the author of the notes.
// Returns { skipped: reason } or { failures: [...], section, before, pins: [...] }: `pins` are the failures of the
// pins of rebom at the same ref as the record of the release (none when the record cannot be read).
export function checkRelease(tag, body, repo, options = {}) {
    if (!isProductTag(tag)) {
        // a tag that starts with a digit is a version of ReARM in a form this check does not know (a typing
        // error, or a new way of numbering releases): refused, so the check is never switched off unseen
        if (typeof tag === 'string' && /^[0-9]/.test(tag)) return { failures: [NOT_THE_FORM(tag)] }
        return { skipped: 'the tag ' + JSON.stringify(tag) + ' is not a ReARM release tag' }
    }
    if (repo.shallow()) return { failures: ['the checkout is shallow: the release before this one cannot be read; fetch the whole history with its tags'] }
    const tags = repo.tags()
    let ref = 'refs/tags/' + tag
    if (options.at !== undefined) {
        const commit = repo.commit(options.at)
        if (commit === null) return { failures: ['--at ' + JSON.stringify(options.at) + ' names no commit of this checkout'] }
        if (tags.includes(tag) && repo.commit(ref) !== commit) {
            return { failures: ['the tag ' + tag + ' exists and is not at the commit --at names: leave --at out to read the release as tagged'] }
        }
        ref = commit
    } else if (!tags.includes(tag)) {
        return { failures: [options.author ? TAG_NOT_MADE(tag) : TAG_NOT_HERE(tag)] }
    }
    const before = previousTag(tags, tag)
    if (before === null) {
        return { failures: ['no ReARM release tag before ' + tag + ' is in this checkout: fetch the tags (ReARM has releases before every release this check reads)'] }
    }
    const path = 'documentation_site/' + RECORD
    const nowText = repo.read(ref, path)
    const beforeText = repo.read('refs/tags/' + before, path)
    if (nowText === null && beforeText === null) return { skipped: 'neither ' + before + ' nor ' + tag + ' carries a change record' }
    if (nowText === null) return { failures: ['the release ' + before + ' carried the change record and ' + tag + ' does not'] }
    let section
    let now
    try {
        now = parseRecord(nowText)
        section = expectedSection(beforeText === null ? null : parseRecord(beforeText), now)
    } catch (e) {
        return { failures: [e.message + ' (the release before is ' + before + ')'], before }
    }
    const where = ref.startsWith('refs/tags/') ? tag : 'the commit ' + ref
    return { failures: bodyFailures(body, section), section, before, pins: pinFailures(now, rebomPinsAt(repo, ref), where) }
}

function git(args) {
    return execFileSync('git', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024,
        env: { ...process.env, LC_ALL: 'C' } })
}

// What may be read: the ref of a release tag, or a commit by its 40 hex digits. Nothing else reaches git as a ref.
export function isReadableRef(ref) {
    return typeof ref === 'string' && (/^[0-9a-f]{40}$/.test(ref) || (ref.startsWith('refs/tags/') && isProductTag(ref.slice(10))))
}

// A revision the author of the notes may give to --at: a commit id, HEAD, a branch or a tag; never an option.
export function isRevision(rev) {
    return typeof rev === 'string' && /^[A-Za-z0-9][A-Za-z0-9._\/-]{0,199}$/.test(rev) && !rev.includes('..')
}

export const gitRepo = {
    shallow: () => git(['rev-parse', '--is-shallow-repository']).trim() !== 'false',
    tags: () => git(['tag', '--list']).split('\n').filter(t => t !== ''),
    // The commit a revision names, as 40 hex digits; null when it names none.
    commit: rev => {
        if (!isRevision(rev)) return null
        try {
            const id = git(['rev-parse', '--verify', '--quiet', rev + '^{commit}']).trim()
            return /^[0-9a-f]{40}$/.test(id) ? id : null
        } catch (e) {
            return null
        }
    },
    // null only when git lists the tree of the ref and the path is not in it; every other failure throws.
    // --full-tree: the path is read from the root of the repository, whatever folder the script is run in.
    read: (ref, path) => {
        if (!isReadableRef(ref)) throw new Error('not a release tag or a commit: ' + JSON.stringify(ref))
        const listed = git(['ls-tree', '--full-tree', '--name-only', ref, '--', path])
        if (listed === '') return null
        if (listed !== path + '\n') throw new Error('git lists ' + JSON.stringify(listed) + ' for ' + path + ' at ' + ref)
        return git(['show', ref + ':' + path])
    },
    // The paths git lists in a folder of the tree of the ref, read from the root of the repository.
    list: (ref, dir) => {
        if (!isReadableRef(ref)) throw new Error('not a release tag or a commit: ' + JSON.stringify(ref))
        return git(['ls-tree', '--full-tree', '--name-only', ref, '--', dir + '/']).split('\n').filter(l => l !== '')
    }
}

// The arguments of `section`: <tag> [<file with the notes>] [--at <commit>], --at anywhere after the command.
// Returns { tag, notes, at } or null when they are not that.
export function sectionArguments(args) {
    const plain = []
    let at
    for (let i = 0; i < args.length; i++) {
        if (args[i] === '--at') {
            if (at !== undefined || i + 1 >= args.length) return null
            at = args[++i]
        } else if (args[i].startsWith('-')) return null
        else plain.push(args[i])
    }
    if (plain.length < 1 || plain.length > 2) return null
    return { tag: plain[0], notes: plain[1], at }
}

export const HOW_TO_MEND = 'Put the lines printed above into the release notes, once, on lines of their own and outside a code block;'
    + ' saving the notes of a published release runs this check again.'

export const USAGE = 'usage: regulated-outputs.mjs pages | pins | release | section <tag> [<file with the release notes>] [--at <commit>]'
export const HOW_TO_MEND_PINS = 'The pins of rebom and the change record disagree at this commit: the release notes cannot settle it.'
    + ' Record the move in ReARM Pro, copy the record here, and run this again.'

export function main(argv, env) {
    const [command, ...rest] = argv
    if (command === 'pages' && rest.length === 0) {
        const pages = {}
        for (const [key, file] of Object.entries(PAGES)) pages[key] = existsSync(file) ? readFileSync(file) : null
        const failures = pageFailures(parseRecord(readFileSync(RECORD, 'utf8')), pages, NOT_COMPARED, PINS)
        failures.forEach(f => console.error(f))
        return failures.length === 0 ? 0 : 1
    }
    if (command === 'pins' && rest.length === 0) {
        // the push job: the record and the pins of rebom in the commit checked out, read through git from the root
        const head = gitRepo.commit('HEAD')
        const text = head === null ? null : gitRepo.read(head, 'documentation_site/' + RECORD)
        if (text === null) {
            console.error('the change record documentation_site/' + RECORD + ' is not in the commit checked out: the pins of rebom have'
                + ' nothing to be compared with')
            return 1
        }
        const pins = rebomPinsAt(gitRepo, head)
        const failures = pinFailures(parseRecord(text), pins, 'the commit ' + head)
        failures.forEach(f => console.error(f))
        if (failures.length === 0) console.log('the pins of rebom are the ones the change record names: ' + PINS.map(k => k + ' ' + pins.values[k]).join(', '))
        return failures.length === 0 ? 0 : 1
    }
    let tag
    let body = null
    let notes
    const options = {}
    if (command === 'release' && rest.length === 0) {
        const event = JSON.parse(readFileSync(env.GITHUB_EVENT_PATH, 'utf8'))
        tag = event.release.tag_name
        body = event.release.body
    } else if (command === 'section' && sectionArguments(rest) !== null) {
        const given = sectionArguments(rest)
        tag = given.tag
        notes = given.notes
        body = notes ? readFileSync(notes, 'utf8') : null
        options.author = true
        if (given.at !== undefined) options.at = given.at
    } else {
        console.error(USAGE)
        return 2
    }
    const result = checkRelease(tag, body, gitRepo, options)
    if (result.skipped) {
        console.log('not checked: ' + result.skipped)
        return 0
    }
    if (result.section) console.log(result.section)
    // the author of the notes sees which release this one was compared with: a checkout without the newest tags compares with an older one
    if (command === 'section' && result.before) console.error('compared with the release before it in this checkout: ' + result.before)
    // `section <tag>` alone prints the section for the author of the notes; with no notes to compare, only the pins remain
    const failures = command === 'section' && !notes && result.section ? [] : result.failures
    const pins = result.pins || []
    failures.forEach(f => console.error(f))
    if (failures.length > 0 && result.section) console.error(HOW_TO_MEND)
    pins.forEach(f => console.error(f))
    if (pins.length > 0) console.error(HOW_TO_MEND_PINS)
    return failures.length + pins.length === 0 ? 0 : 1
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    process.exit(main(process.argv.slice(2), process.env))
}
